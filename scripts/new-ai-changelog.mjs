#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");

const args = process.argv.slice(2);
function getArg(flag) {
  const idx = args.indexOf(flag);
  return idx !== -1 && idx + 1 < args.length ? args[idx + 1] : undefined;
}

let releaseName = getArg("--release-name");
const taskIdsArg = getArg("--task-ids");

if (!releaseName) {
  const now = new Date();
  const ts = `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, "0")}${String(now.getDate()).padStart(2, "0")}-${String(now.getHours()).padStart(2, "0")}${String(now.getMinutes()).padStart(2, "0")}${String(now.getSeconds()).padStart(2, "0")}`;
  releaseName = `unreleased-${ts}`;
}

const changelogPath = join(repoRoot, "CHANGELOG.md");
const tasksDir = join(repoRoot, ".ai", "tasks");

const taskFiles = [];
if (taskIdsArg) {
  const taskIds = taskIdsArg.split(",");
  for (const tid of taskIds) {
    const glob = join(tasksDir, "**", `${tid}.md`);
    // use sync readdir approach
  }
} else if (existsSync(tasksDir)) {
  function walkDir(dir) {
    const entries = readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = join(dir, entry.name);
      if (entry.isDirectory()) {
        walkDir(fullPath);
      } else if (entry.isFile() && entry.name !== "README.md" && entry.name.endsWith(".md")) {
        taskFiles.push({ name: entry.name.replace(/\.md$/, ""), fullPath });
      }
    }
  }
  walkDir(tasksDir);
}

const taskLines = [];
for (const tf of taskFiles.sort((a, b) => a.fullPath.localeCompare(b.fullPath))) {
  const firstLine = readFileSync(tf.fullPath, "utf-8").split("\n")[0] || "";
  const trimmed = firstLine.replace(/^#/, "").trim();
  taskLines.push(`- ${trimmed || tf.name}`);
}

if (taskLines.length === 0) {
  taskLines.push("- No task bundles were found for this release window.");
}

const now = new Date();
const dateStr = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(now.getDate()).padStart(2, "0")}`;

const newSection = `## ${releaseName} - ${dateStr}

### Changed

${taskLines.join("\n")}

### Notes

- Generated by scripts/new-ai-changelog.mjs

`;

let updated;
if (existsSync(changelogPath)) {
  const existing = readFileSync(changelogPath, "utf-8");
  if (existing.includes(`## ${releaseName} -`)) {
    console.log(changelogPath);
    process.exit(0);
  }
  if (existing.startsWith("# Changelog")) {
    updated = existing.replace(/(# Changelog\s*)/, `$1\n${newSection}\n`);
  } else {
    updated = `# Changelog\n\n${newSection}\n${existing}`;
  }
} else {
  updated = `# Changelog\n\n${newSection}`;
}

writeFileSync(changelogPath, updated, "utf-8");
console.log(changelogPath);
