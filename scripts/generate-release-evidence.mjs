function renderMarkdown(input) {
  const gateRows = input.gates.map((gate) => `| \`${gate.command}\` | ${gate.status} |`).join("\n");
  const fileRows = input.files
    .map((entry) => `| \`${entry.file}\` | ${entry.exists ? "yes" : "no"} | ${entry.bytes} |`)
    .join("\n");
  const externalEvidenceRows = input.productionExternalEvidenceRequired
    .map((entry) => `- ${entry}`)
    .join("\n");
  const moduleRows = input.businessModules
    .map(
      (entry) =>
        `| ${entry.name} | ${entry.boundedContext} | ${entry.status} | ${entry.requiredGates
          .map((gate) => `\`${gate}\``)
          .join(", ")} |`,
    )
    .join("\n");
  const moduleCriteriaRows = input.businessModules
    .flatMap((entry) => entry.releaseCriteria.map((criterion) => `- ${entry.name}: ${criterion}`))
    .join("\n");

  return `# SAPTM Release Evidence

## Metadata

| Field | Value |
| --- | --- |
| Generated At | ${input.generatedAt} |
| Repository | ${input.repository} |
| Ref | ${input.ref} |
| SHA | ${input.sha} |
| Run ID | ${input.runId} |
| Decision | ${input.decision} |

## CI Gates

| Command | Status |
| --- | --- |
${gateRows}

## Evidence Files

| File | Exists | Bytes |
| --- | --- | --- |
${fileRows}

## Business Module Evidence

| Module | Context | Status | Required Gates |
| --- | --- | --- | --- |
${moduleRows}

## Business Module Release Criteria

${moduleCriteriaRows}

## Production External Evidence Required

${externalEvidenceRows}
`;
}
