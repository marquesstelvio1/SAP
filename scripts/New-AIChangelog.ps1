param(
    [string]$ReleaseName = ("unreleased-" + (Get-Date -Format "yyyyMMdd-HHmmss")),
    [string[]]$TaskIds
)

$repoRoot = Split-Path -Parent $PSScriptRoot
$changelogPath = Join-Path $repoRoot "CHANGELOG.md"

if ($TaskIds -and $TaskIds.Count -gt 0) {
    $taskFiles = foreach ($taskId in $TaskIds) {
        Get-ChildItem -Path (Join-Path $repoRoot ".ai/tasks") -Recurse -File |
            Where-Object { $_.BaseName -eq $taskId -and $_.BaseName -ne "README" }
    }
} else {
    $taskFiles = Get-ChildItem -Path (Join-Path $repoRoot ".ai/tasks") -Recurse -File -ErrorAction SilentlyContinue |
        Where-Object { $_.BaseName -ne "README" }
}

$taskLines = foreach ($taskFile in $taskFiles | Sort-Object FullName -Unique) {
    $firstLine = (Get-Content -LiteralPath $taskFile.FullName -TotalCount 1)
    if ([string]::IsNullOrWhiteSpace($firstLine)) {
        "- $($taskFile.BaseName)"
    } else {
        "- $($firstLine.TrimStart('#').Trim())"
    }
}

if (-not $taskLines) {
    $taskLines = @("- No task bundles were found for this release window.")
}

$newSection = @"
## $ReleaseName - $(Get-Date -Format "yyyy-MM-dd")

### Changed

$($taskLines -join "`r`n")

### Notes

- Generated by scripts/New-AIChangelog.ps1

"@

if (Test-Path -LiteralPath $changelogPath) {
    $existing = Get-Content -LiteralPath $changelogPath -Raw
    if ($existing -match [regex]::Escape("## $ReleaseName -")) {
        Write-Output $changelogPath
        return
    }
    if ($existing.StartsWith("# Changelog")) {
        $updated = $existing -replace "(# Changelog\s*)", "`$1`r`n$newSection`r`n"
    } else {
        $updated = "# Changelog`r`n`r`n$newSection`r`n$existing"
    }
} else {
    $updated = "# Changelog`r`n`r`n$newSection"
}

Set-Content -LiteralPath $changelogPath -Value $updated -Encoding UTF8
Write-Output $changelogPath
