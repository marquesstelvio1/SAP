param(
    [Parameter(Mandatory = $true)]
    [ValidateSet("diagnostic", "delivery", "release")]
    [string]$Workflow,

    [string]$Domain = "frontend",
    [string]$TaskId,
    [string]$Feature = "bootstrap-task",
    [string]$Priority = "high",
    [string]$ReleaseName
)

$repoRoot = Split-Path -Parent $PSScriptRoot
$executionDir = Join-Path $repoRoot ".ai/executions"

New-Item -ItemType Directory -Force -Path $executionDir | Out-Null

$outputs = New-Object System.Collections.Generic.List[string]

function Add-WorkflowOutput {
    param(
        [System.Collections.IEnumerable]$Items
    )

    foreach ($item in $Items) {
        if (-not [string]::IsNullOrWhiteSpace([string]$item)) {
            $outputs.Add([string]$item)
        }
    }
}

switch ($Workflow) {
    "diagnostic" {
        $diagnosticOutput = & (Join-Path $PSScriptRoot "New-AIDiagnostic.ps1") `
            -Domain $Domain `
            -Title $Feature `
            -Severity $Priority `
            -Impact "Diagnostic generated from AI workflow orchestration." `
            -Evidence "Generated by scripts/Invoke-AIWorkflow.ps1"
        Add-WorkflowOutput -Items $diagnosticOutput

        $diagnosticPath = $diagnosticOutput | Select-Object -First 1
        if (-not [string]::IsNullOrWhiteSpace($diagnosticPath)) {
            Add-WorkflowOutput -Items (& (Join-Path $PSScriptRoot "New-AITaskFromDiagnostic.ps1") -DiagnosticPath $diagnosticPath -TaskId $TaskId -Priority $Priority)
            break
        }

        Add-WorkflowOutput -Items (& (Join-Path $PSScriptRoot "New-AITaskBundle.ps1") -Domain $Domain -Feature $Feature -Priority $Priority -TaskId $TaskId)
    }
    "delivery" {
        if ([string]::IsNullOrWhiteSpace($TaskId)) {
            $TaskId = "AI-{0}" -f (Get-Date -Format "yyyyMMdd-HHmmss")
        }

        $taskPath = Join-Path $repoRoot ".ai/tasks/$Domain/$TaskId.md"
        if (-not (Test-Path -LiteralPath $taskPath)) {
            Add-WorkflowOutput -Items (& (Join-Path $PSScriptRoot "New-AITaskBundle.ps1") -Domain $Domain -Feature $Feature -Priority $Priority -TaskId $TaskId)
        }

        Add-WorkflowOutput -Items (& (Join-Path $PSScriptRoot "New-AITestPlan.ps1") -Domain $Domain -TaskId $TaskId)
        Add-WorkflowOutput -Items (& (Join-Path $PSScriptRoot "New-AIDocumentationPack.ps1") -Domain $Domain -TaskId $TaskId -Summary "Document delivery artifact for $Feature")
        Add-WorkflowOutput -Items (& (Join-Path $PSScriptRoot "New-AIPullRequestDraft.ps1") -Domain $Domain -TaskId $TaskId -Title "$TaskId - $Feature" -Summary "Deliver $Feature in $Domain")
        Add-WorkflowOutput -Items (& (Join-Path $PSScriptRoot "New-AIGovernanceReview.ps1") -Domain $Domain -TaskId $TaskId -Risk $Priority)
    }
    "release" {
        if ([string]::IsNullOrWhiteSpace($ReleaseName)) {
            $ReleaseName = "release-{0}" -f (Get-Date -Format "yyyyMMdd-HHmmss")
        }
        $outputs.Add((& (Join-Path $PSScriptRoot "New-AIChangelog.ps1") -ReleaseName $ReleaseName))
    }
}

$reportDomain = if ($Workflow -eq "release") { "all" } else { $Domain }
$reportPath = Join-Path $executionDir ("{0}-{1}-{2}.md" -f (Get-Date -Format "yyyyMMdd-HHmmss"), $Workflow, $reportDomain)
$reportContent = @"
# Execution Report

## Workflow

$Workflow

## Domain

$reportDomain

## Task

$TaskId

## Outputs

$($outputs | ForEach-Object { "- $_" } | Out-String)

## Risks

- validate generated artifacts before external sync or merge

## Follow-up

- review governance gates
- sync approved artifacts to GitHub, Jira, and Linear when applicable
"@

Set-Content -LiteralPath $reportPath -Value $reportContent.Trim() -Encoding UTF8
Write-Output $reportPath
