function extractStringArray(file, constName) {
  const source = readFileSync(join(root, file), "utf8");
  const match = source.match(
    new RegExp(`export const ${constName} = \\[(?<body>[\\s\\S]*?)\\] as const;`),
  );

  if (!match?.groups?.body) {
    throw new Error(`Unable to read ${constName} from ${file}`);
  }

  return [...match.groups.body.matchAll(/"([^"]+)"/g)].map((entry) => entry[1]).sort();
}

function extractObjectArrayKeys(file, constName) {
  const source = readFileSync(join(root, file), "utf8");
  const match = source.match(
    new RegExp(`export const ${constName} = \\[(?<body>[\\s\\S]*?)\\] as const;`),
  );

  if (!match?.groups?.body) {
    throw new Error(`Unable to read ${constName} from ${file}`);
  }

  return [...match.groups.body.matchAll(/key: "([^"]+)"/g)].map((entry) => entry[1]).sort();
}

function symmetricDifference(left, right) {
  const leftSet = new Set(left);
  const rightSet = new Set(right);

  return [
    ...left.filter((value) => !rightSet.has(value)),
    ...right.filter((value) => !leftSet.has(value)),
  ].sort();
}
