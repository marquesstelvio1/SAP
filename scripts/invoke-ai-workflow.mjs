#!/usr/bin/env node
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");

const args = process.argv.slice(2);
function getArg(flag) {
  const idx = args.indexOf(flag);
  return idx !== -1 && idx + 1 < args.length ? args[idx + 1] : undefined;
}

const workflow = getArg("--workflow");
const domain = getArg("--domain") || "frontend";
let taskId = getArg("--task-id");
const feature = getArg("--feature") || "bootstrap-task";
const priority = getArg("--priority") || "high";
const releaseName = getArg("--release-name");

if (!workflow || !["diagnostic", "delivery", "release"].includes(workflow)) {
  console.error(
    "Usage: invoke-ai-workflow.mjs --workflow diagnostic|delivery|release [--domain <d>] [--task-id <id>] [--feature <f>] [--priority <p>] [--release-name <name>]",
  );
  process.exit(1);
}

const executionDir = join(repoRoot, ".ai", "executions");
mkdirSync(executionDir, { recursive: true });

const outputs = [];

function addWorkflowOutput(items) {
  if (Array.isArray(items)) {
    for (const item of items) {
      if (item && typeof item === "string" && item.trim()) {
        outputs.push(item.trim());
      }
    }
  } else if (typeof items === "string" && items.trim()) {
    outputs.push(items.trim());
  }
}

function runScript(scriptName, scriptArgs) {
  const scriptPath = join(__dirname, scriptName);
  const argStr = Object.entries(scriptArgs)
    .filter(([, v]) => v !== undefined && v !== null)
    .map(([k, v]) => `--${k} "${v}"`)
    .join(" ");
  const cmd = `node "${scriptPath}" ${argStr}`;
  try {
    const stdout = execSync(cmd, { encoding: "utf-8" });
    return stdout.trim().split("\n").filter(Boolean);
  } catch (err) {
    console.error(`Error running ${scriptName}:`, err.message);
    return [];
  }
}

switch (workflow) {
  case "diagnostic": {
    const diagnosticOutput = runScript("new-ai-diagnostic.mjs", {
      domain,
      title: feature,
      severity: priority,
      impact: "Diagnostic generated from AI workflow orchestration.",
      evidence: "Generated by scripts/invoke-ai-workflow.mjs",
    });
    addWorkflowOutput(diagnosticOutput);

    const diagnosticPath = diagnosticOutput[0];
    if (diagnosticPath) {
      addWorkflowOutput(
        runScript("new-ai-task-from-diagnostic.mjs", {
          "diagnostic-path": diagnosticPath,
          "task-id": taskId,
          priority,
        }),
      );
    } else {
      addWorkflowOutput(
        runScript("new-ai-task-bundle.mjs", {
          domain,
          feature,
          priority,
          "task-id": taskId,
        }),
      );
    }
    break;
  }
  case "delivery": {
    if (!taskId) {
      const now = new Date();
      const ts = `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, "0")}${String(now.getDate()).padStart(2, "0")}-${String(now.getHours()).padStart(2, "0")}${String(now.getMinutes()).padStart(2, "0")}${String(now.getSeconds()).padStart(2, "0")}`;
      taskId = `AI-${ts}`;
    }

    const taskDir = join(repoRoot, ".ai", "tasks", domain);
    const taskPath = join(taskDir, `${taskId}.md`);
    if (!existsSync(taskPath)) {
      addWorkflowOutput(
        runScript("new-ai-task-bundle.mjs", { domain, feature, priority, "task-id": taskId }),
      );
    }

    addWorkflowOutput(runScript("new-ai-test-plan.mjs", { domain, "task-id": taskId }));
    addWorkflowOutput(
      runScript("new-ai-documentation-pack.mjs", {
        domain,
        "task-id": taskId,
        summary: `Document delivery artifact for ${feature}`,
      }),
    );
    addWorkflowOutput(
      runScript("new-ai-pull-request-draft.mjs", {
        domain,
        "task-id": taskId,
        title: `${taskId} - ${feature}`,
        summary: `Deliver ${feature} in ${domain}`,
      }),
    );
    addWorkflowOutput(
      runScript("new-ai-governance-review.mjs", { domain, "task-id": taskId, risk: priority }),
    );
    break;
  }
  case "release": {
    const rn =
      releaseName ||
      (() => {
        const now = new Date();
        const ts = `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, "0")}${String(now.getDate()).padStart(2, "0")}-${String(now.getHours()).padStart(2, "0")}${String(now.getMinutes()).padStart(2, "0")}${String(now.getSeconds()).padStart(2, "0")}`;
        return `release-${ts}`;
      })();
    addWorkflowOutput(runScript("new-ai-changelog.mjs", { "release-name": rn }));
    break;
  }
}

const reportDomain = workflow === "release" ? "all" : domain;
const now = new Date();
const ts = `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, "0")}${String(now.getDate()).padStart(2, "0")}-${String(now.getHours()).padStart(2, "0")}${String(now.getMinutes()).padStart(2, "0")}${String(now.getSeconds()).padStart(2, "0")}`;
const reportPath = join(executionDir, `${ts}-${workflow}-${reportDomain}.md`);

const reportContent = `# Execution Report

## Workflow

${workflow}

## Domain

${reportDomain}

## Task

${taskId || ""}

## Outputs

${outputs.map((o) => `- ${o}`).join("\n")}

## Risks

- validate generated artifacts before external sync or merge

## Follow-up

- review governance gates
- sync approved artifacts to GitHub, Jira, and Linear when applicable
`;

writeFileSync(reportPath, reportContent.trim(), "utf-8");
console.log(reportPath);
