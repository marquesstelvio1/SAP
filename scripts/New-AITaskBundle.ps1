param(
    [Parameter(Mandatory = $true)]
    [string]$Domain,

    [Parameter(Mandatory = $true)]
    [string]$Feature,

    [string]$Priority = "high",
    [string]$Epic = "EPIC-BOOTSTRAP",
    [string]$TaskId
)

$repoRoot = Split-Path -Parent $PSScriptRoot
$manifestPath = Join-Path $repoRoot ".ai/operating-system.json"

if (-not (Test-Path -LiteralPath $manifestPath)) {
    throw "Missing operating system manifest at $manifestPath"
}

$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
$domains = $manifest.domains.PSObject.Properties.Name

if ($domains -notcontains $Domain) {
    throw "Unknown domain '$Domain'. Allowed values: $($domains -join ', ')"
}

if ([string]::IsNullOrWhiteSpace($TaskId)) {
    $TaskId = "AI-{0}" -f (Get-Date -Format "yyyyMMdd-HHmmss")
}

$ownerAgent = $manifest.domains.$Domain.ownerAgent
$taskDir = Join-Path $repoRoot ".ai/tasks/$Domain"
$integrationDir = Join-Path $repoRoot ".ai/reports/integrations"
$taskPath = Join-Path $taskDir "$TaskId.md"
$jiraTemplatePath = Join-Path $repoRoot "jira/task-payload-template.json"
$linearTemplatePath = Join-Path $repoRoot "linear/issue-payload-template.json"

New-Item -ItemType Directory -Force -Path $taskDir, $integrationDir | Out-Null

$taskContent = @"
# $TaskId - $Feature

## Domain

$Domain

## Objective

Deliver $Feature with controlled scope and auditable outputs.

## Scope

- Implement the approved change surface for $Domain.
- Respect rules from docs/rules/domains/$Domain.md and docs/rules/global.md.
- Keep outputs compatible with the current architecture and governance gates.

## Acceptance criteria

- Task objective is implemented for $Domain.
- Domain rules are respected.
- Tests, docs, PR metadata, and rollback notes are generated.
- Governance risks are explicit.

## Rules

- Owner agent: $ownerAgent
- Priority: $Priority
- Epic: $Epic

## Dependencies

- Diagnostic source
- Architecture review when cross-domain impact exists
- QA validation before release

## Test plan

- Generated by scripts/New-AITestPlan.ps1

## Documentation updates

- Generated by scripts/New-AIDocumentationPack.ps1

## Rollout and rollback

- Must be defined before merge if the task affects production behavior.
"@

Set-Content -LiteralPath $taskPath -Value $taskContent -Encoding UTF8

function Expand-Template {
    param(
        [string]$Template,
        [hashtable]$Values
    )

    $result = $Template
    foreach ($key in $Values.Keys) {
        $result = $result.Replace("{{$key}}", $Values[$key])
    }
    return $result
}

$replacements = @{
    TASK_TITLE = $Feature
    TASK_DESCRIPTION = "AI-generated task bundle for $Feature"
    DOMAIN = $Domain
    OWNER_AGENT = $ownerAgent
    RISK_LEVEL = $Priority
    ROLLBACK = "Revert branch and redeploy previous known-good state"
    PRIORITY = $Priority
    PR_LINK = ""
}

$jiraContent = Expand-Template -Template (Get-Content -LiteralPath $jiraTemplatePath -Raw) -Values $replacements
$linearContent = Expand-Template -Template (Get-Content -LiteralPath $linearTemplatePath -Raw) -Values $replacements

$jiraPath = Join-Path $integrationDir "$TaskId-jira.json"
$linearPath = Join-Path $integrationDir "$TaskId-linear.json"

Set-Content -LiteralPath $jiraPath -Value $jiraContent -Encoding UTF8
Set-Content -LiteralPath $linearPath -Value $linearContent -Encoding UTF8

Write-Output $taskPath
Write-Output $jiraPath
Write-Output $linearPath

