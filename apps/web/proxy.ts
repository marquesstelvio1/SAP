import type { NextRequest } from "next/server";
import { NextResponse } from "next/server";

const PUBLIC_PATHS = [
  "/sign-in",
  "/forgot-password",
  "/reset-password",
  "/two-factor",
  "/accept-invitation",
] as const;

const STATIC_PREFIXES = [
  "/_next/static/",
  "/__nextjs_original-stack-frame",
  "/sentry-tunnel",
  "/favicon.ico",
  "/robots.txt",
] as const;

const STATIC_SUFFIXES = [".map", ".webmanifest"] as const;

const RATE_LIMIT_WINDOW_MS = 60_000;
const RATE_LIMIT_MAX = 200;
const RATE_LIMIT_BURST = 20;
const RATE_LIMIT_CLEANUP_INTERVAL_MS = 60_000;
const RATE_LIMIT_MAX_ENTRIES = 10_000;

type IpEntry = {
  count: number;
  burstRemaining: number;
  resetAt: number;
};

const localRateMap = new Map<string, IpEntry>();

function cleanupRateMap(): void {
  const now = Date.now();
  for (const [ip, entry] of localRateMap) {
    if (now >= entry.resetAt) {
      localRateMap.delete(ip);
    }
  }
  if (localRateMap.size > RATE_LIMIT_MAX_ENTRIES) {
    const sorted = [...localRateMap.entries()].sort((a, b) => a[1].resetAt - b[1].resetAt);
    const toDelete = sorted.slice(0, sorted.length - RATE_LIMIT_MAX_ENTRIES);
    for (const [ip] of toDelete) {
      localRateMap.delete(ip);
    }
  }
}

setInterval(cleanupRateMap, RATE_LIMIT_CLEANUP_INTERVAL_MS).unref();

function isRateLimited(ip: string): boolean {
  const now = Date.now();
  let entry = localRateMap.get(ip);

  if (entry === undefined || now >= entry.resetAt) {
    entry = {
      count: 1,
      burstRemaining: RATE_LIMIT_BURST,
      resetAt: now + RATE_LIMIT_WINDOW_MS,
    };
    localRateMap.set(ip, entry);
    return false;
  }

  entry.count++;

  if (entry.count <= RATE_LIMIT_MAX) {
    return false;
  }

  if (entry.burstRemaining > 0) {
    entry.burstRemaining--;
    return false;
  }

  return true;
}

function isPublicPath(pathname: string): boolean {
  return (
    PUBLIC_PATHS.some((p) => pathname === p || pathname.startsWith(`${p}/`)) ||
    pathname.startsWith("/api/")
  );
}

function isStaticAsset(pathname: string): boolean {
  return (
    STATIC_PREFIXES.some((p) => pathname.startsWith(p)) ||
    STATIC_SUFFIXES.some((s) => pathname.endsWith(s))
  );
}

function buildCsp(nonce: string, isDev: boolean): string {
  const scriptSrc = isDev
    ? `'nonce-${nonce}' 'strict-dynamic' 'unsafe-eval'`
    : `'nonce-${nonce}' 'strict-dynamic'`;

  // Next.js 16 automatically attaches nonce to framework scripts, page JS,
  // inline styles generated by Next.js, and <Script> components with nonce prop.
  // style-src-attr 'unsafe-inline' is required for Radix UI / floating-ui
  // which set inline style attributes at runtime.
  const directives = [
    `default-src 'self'`,
    `base-uri 'self'`,
    `form-action 'self'`,
    `frame-ancestors 'none'`,
    `object-src 'none'`,
    `img-src 'self' data: blob:`,
    `font-src 'self' data:`,
    `script-src 'self' ${scriptSrc}`,
    `style-src 'self' 'nonce-${nonce}'`,
    `style-src-attr 'unsafe-inline'`,
    `connect-src 'self'`,
    `worker-src 'self' blob:`,
    `frame-src 'none'`,
    `upgrade-insecure-requests`,
  ];
  return directives.join("; ");
}

function buildResponse(request: NextRequest, nonce: string, isDev: boolean): NextResponse {
  const csp = buildCsp(nonce, isDev);

  // Forward nonce + CSP to React tree via request headers
  // Next.js 16 reads x-nonce and auto-attaches it to inline scripts/styles
  const requestHeaders = new Headers(request.headers);
  requestHeaders.set("x-nonce", nonce);
  requestHeaders.set("Content-Security-Policy", csp);

  const response = NextResponse.next({
    request: { headers: requestHeaders },
  });

  response.headers.set("Content-Security-Policy", csp);
  response.headers.set("Strict-Transport-Security", "max-age=31536000; includeSubDomains; preload");
  response.headers.set("X-Content-Type-Options", "nosniff");
  response.headers.set("Referrer-Policy", "strict-origin-when-cross-origin");
  response.headers.set("X-Frame-Options", "DENY");
  response.headers.set(
    "Permissions-Policy",
    "camera=(), geolocation=(), microphone=(), interest-cohort=(), payment=(), usb=()",
  );
  response.headers.set("Cross-Origin-Opener-Policy", "same-origin");
  response.headers.set("Cross-Origin-Resource-Policy", "same-origin");

  if (request.headers.get("accept")?.includes("text/html")) {
    response.headers.set("Cache-Control", "private, no-cache, no-store");
    response.headers.set("Vary", "Cookie");
  }

  return response;
}

const SESSION_COOKIE_NAMES = [
  "better-auth.session_token",
  "__Secure-better-auth.session_token",
] as const;

const CHUNKED_PREFIXES = [
  "better-auth.session_token.chunk",
  "__Secure-better-auth.session_token.chunk",
] as const;

function hasValidSessionCookie(request: NextRequest): boolean {
  for (const name of SESSION_COOKIE_NAMES) {
    const cookie = request.cookies.get(name);
    if (cookie?.value && cookie.value.length > 20) {
      return true;
    }
  }

  return Array.from(request.cookies.getAll()).some((c) =>
    CHUNKED_PREFIXES.some((p) => c.name.startsWith(p)),
  );
}

export function proxy(request: NextRequest) {
  const url = new URL(request.url);
  const pathname = url.pathname;
  const isDev = process.env.NODE_ENV === "development";

  const nonce = Buffer.from(crypto.randomUUID()).toString("base64");

  if (isPublicPath(pathname) || isStaticAsset(pathname)) {
    return buildResponse(request, nonce, isDev);
  }

  const forwardedFor = request.headers.get("x-forwarded-for");
  const ip = forwardedFor?.split(",").at(0)?.trim() ?? "127.0.0.1";

  if (isRateLimited(ip)) {
    if (request.headers.get("accept")?.includes("text/html")) {
      return new NextResponse(null, { status: 429, statusText: "Too Many Requests" });
    }
    return buildResponse(request, nonce, isDev);
  }

  if (hasValidSessionCookie(request)) {
    return buildResponse(request, nonce, isDev);
  }

  const signInUrl = new URL("/sign-in", url);
  signInUrl.searchParams.set("next", pathname);
  return NextResponse.redirect(signInUrl);
}
